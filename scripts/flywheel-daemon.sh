install_wrapper() {
  local src="${FLYWHEEL_DIR}/scripts/flywheel-lead-wrapper.sh"
  local dst="${FLYWHEEL_BIN}/flywheel-lead-wrapper.sh"

  if [ ! -f "$src" ]; then
    error "Wrapper source not found: ${src}"
