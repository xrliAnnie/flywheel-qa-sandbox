#!/bin/bash
# FLY-74: Lead daemon management CLI.
# Generates launchd plists from manifests, manages Lead lifecycle.
#
# Usage: flywheel-daemon.sh <command> [options]
#
# Commands:
#   install [lead-id|--all]   Generate plist + register with launchd
#   uninstall [lead-id|--all] Unregister from launchd + remove plist
#   restart [lead-id|--all]   Stop + start (launchctl kickstart -k)
#   status                    Show all Lead daemon statuses
#   logs [lead-id]            Tail Lead log file
#
# Lead identification uses {project}-{lead-id} from manifest filenames
# to avoid cross-project collisions (e.g., two projects both having
# a "product-lead"). The CLI accepts just lead-id for convenience
# when there's no ambiguity.
#
# Prerequisites:
#   - jq installed
#   - Manifests exist at ~/.flywheel/manifests/ (generated by claude-lead.sh)
#   - ~/.flywheel/.env contains bot tokens and config
#
# The wrapper script (flywheel-lead-wrapper.sh) is installed to ~/.flywheel/bin/
# automatically on first install.
set -euo pipefail

FLYWHEEL_DIR="${HOME}/Dev/flywheel"
MANIFEST_DIR="${HOME}/.flywheel/manifests"
PLIST_DIR="${HOME}/Library/LaunchAgents"
FLYWHEEL_BIN="${HOME}/.flywheel/bin"
PID_DIR="${HOME}/.flywheel/pids"
PLIST_PREFIX="com.flywheel.lead"
GUI_DOMAIN="gui/$(id -u)"

# FLY-247: test seams — external commands and timeouts are env-injectable so
# the bash test suite can stub launchd/plutil/tmux without touching the real
# system. Defaults are byte-identical to the previous hard-coded behavior.
LAUNCHCTL="${FLYWHEEL_DAEMON_LAUNCHCTL:-launchctl}"
PLUTIL="${FLYWHEEL_DAEMON_PLUTIL:-plutil}"
TMUX_BIN="${FLYWHEEL_DAEMON_TMUX:-tmux}"
STOP_TIMEOUT="${FLYWHEEL_DAEMON_STOP_TIMEOUT:-60}"
VERIFY_TIMEOUT="${FLYWHEEL_DAEMON_VERIFY_TIMEOUT:-60}"
POLL_INTERVAL="${FLYWHEEL_DAEMON_POLL_INTERVAL:-1}"

# FLY-247 §2.6: distinct exit codes per failure phase — fleet picks the right
# recovery branch from the JSON result record + these codes (never from stderr).
EXIT_PREP_FAILED=10
EXIT_STOP_TIMEOUT=20
EXIT_COMMIT_FAILED=30
EXIT_BOOTSTRAP_FAILED=40
EXIT_VERIFY_NOT_STARTED=41
EXIT_VERIFY_ALIVE_UNVERIFIED=42

# ════════════════════════════════════════════════════════════════
# Utility functions
# ════════════════════════════════════════════════════════════════

log() {
  echo "[daemon] $*"
}

error() {
  echo "[daemon] ERROR: $*" >&2
  exit 1
}

# R4-H4: keys flow into filesystem paths (manifests, plists, txn artifacts).
# Reject anything outside a safe identifier grammar — separators, dots-only
# segments, control characters could escape directories or collide files.
validate_key_grammar() {
  local key="$1"
  case "$key" in
    *[!A-Za-z0-9._-]*|""|.|..|*/*) return 1 ;;
  esac
  return 0
}

require_jq() {
  command -v jq >/dev/null 2>&1 || error "jq is required but not found. Install: brew install jq"
}

# Derive a daemon key from manifest filename.
# Manifest: {project}-{lead-id}.json → daemon key: {project}-{lead-id}
# This preserves the project scope that existing Lead infra uses.
daemon_key_from_manifest() {
  local manifest="$1"
  basename "$manifest" .json
}

# Get plist label from daemon key
plist_label() {
  echo "${PLIST_PREFIX}.${1}"
}

# Get plist file path from daemon key
plist_path() {
  echo "${PLIST_DIR}/$(plist_label "$1").plist"
}

# Get log file path from daemon key
log_path() {
  local daemon_key="$1"
  echo "/tmp/flywheel-lead-${daemon_key}.log"
}

# Find manifest file(s) matching a lead-id or daemon-key.
# Returns manifest path(s), one per line.
# Exits 1 if no match found.
find_manifests() {
  local query="$1"
  local found=0

  # Try exact daemon-key match first: {query}.json
  if [ -f "${MANIFEST_DIR}/${query}.json" ]; then
    echo "${MANIFEST_DIR}/${query}.json"
    return 0
  fi

  # Try lead-id suffix match: *-{query}.json
  for f in "${MANIFEST_DIR}"/*-"${query}.json"; do
    if [ -f "$f" ]; then
      echo "$f"
      found=$((found + 1))
    fi
  done

  [ "$found" -gt 0 ] && return 0
  return 1
}

# List all manifest files
list_manifests() {
  for f in "${MANIFEST_DIR}"/*.json; do
    [ -f "$f" ] && echo "$f"
  done
}

# R4-H1: tri-state launchd probe. Echoes one of:
#   "loaded <pid>"  — label loaded; pid 0 = loaded-without-PID (idle KeepAlive)
#   "unloaded"      — DETERMINED not-loaded (launchctl said could-not-find)
#   "error"         — probe failure (binary missing, transport error, unknown
#                     non-zero) → callers must fail-close, never assume unloaded
launchd_probe() {
  local daemon_key="$1"
  local label
  label=$(plist_label "$daemon_key")
  command -v "$LAUNCHCTL" >/dev/null 2>&1 || { echo "error"; return; }
  local out rc
  out=$("$LAUNCHCTL" print "${GUI_DOMAIN}/${label}" 2>&1)
  rc=$?
  if [ "$rc" -eq 0 ]; then
    local pid
    pid=$(printf '%s' "$out" | grep -m1 'pid =' | awk '{print $NF}' || true)
    echo "loaded ${pid:-0}"
    return
  fi
  if printf '%s' "$out" | grep -qiE 'could not find service|no such process'; then
    echo "unloaded"
    return
  fi
  echo "error"
}

# Check if a launchd service is loaded
is_loaded() {
  local daemon_key="$1"
  "$LAUNCHCTL" print "${GUI_DOMAIN}/$(plist_label "$daemon_key")" &>/dev/null
}

# Get PID of a running launchd service (0 if not running)
get_launchd_pid() {
  local daemon_key="$1"
  local label
  label=$(plist_label "$daemon_key")
  local pid
  pid=$("$LAUNCHCTL" print "${GUI_DOMAIN}/${label}" 2>/dev/null | grep -m1 'pid =' | awk '{print $NF}' || true)
  echo "${pid:-0}"
}

