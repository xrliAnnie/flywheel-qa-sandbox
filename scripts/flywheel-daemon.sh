cmd_install() {
  local target="${1:---all}"
  require_jq

  # FLY-247 staged mode (R4#2): `install <exact-key> --staged-dir <dir>` is
  # a different contract from legacy install — it must NOT touch the shared
  # wrapper (Phase W owns that, exactly once per transaction) and must NOT
  # regenerate the canonical plist (it commits the pre-validated staged one).
  local staged_dir=""
  if [ "${2:-}" = "--staged-dir" ]; then
    staged_dir="${3:-}"
    [ -n "$staged_dir" ] || error "install --staged-dir requires a directory argument"
    [ -d "$staged_dir" ] || error "staged dir not found: ${staged_dir}"
    [ "$target" != "--all" ] || error "staged install requires an exact {project}-{lead} key, not --all"
    # Exact key only — no suffix matching in the transactional path.
    install_one_staged "$target" "$staged_dir"
    return $?
  fi

  # Install wrapper (shared by all leads) — legacy behavior preserved.
  install_wrapper

  if [ "$target" = "--all" ]; then
    local count=0
    for manifest in $(list_manifests); do
      install_one_manifest "$manifest"
      count=$((count + 1))
    done
    if [ "$count" -eq 0 ]; then
      log "No manifests found in ${MANIFEST_DIR}/. Run claude-lead.sh first."
    else
      log "Installed ${count} Lead daemon(s)."
    fi
  else
    local manifests
    manifests=$(find_manifests "$target") || error "No manifest for '${target}' in ${MANIFEST_DIR}/"
    local count=0
    while IFS= read -r manifest; do
      install_one_manifest "$manifest"
      count=$((count + 1))
    done <<< "$manifests"
    if [ "$count" -gt 1 ]; then
      log "Installed ${count} Leads matching '${target}'."
    fi
  fi
}

install_one_manifest() {
  local manifest="$1"
  local daemon_key
  daemon_key=$(daemon_key_from_manifest "$manifest")
  local lead_id
  lead_id=$(jq -r '.leadId' "$manifest")

  # Validate manifest
  local project_dir
  project_dir=$(jq -r '.projectDir' "$manifest")
  if [ -z "$project_dir" ] || [ "$project_dir" = "null" ]; then
    error "Manifest missing projectDir: ${manifest}"
  fi

  local label
  label=$(plist_label "$daemon_key")

  # Unload existing if loaded (idempotent reinstall).
  # FLY-247 R1#1: record the old PID and WAIT for it to actually exit
  # (≤STOP_TIMEOUT) instead of the old `sleep 1` guess — bootstrapping while
  # the old supervisor is still draining risks a double instance.
  if is_loaded "$daemon_key"; then
    local old_pid
    old_pid=$(get_launchd_pid "$daemon_key")
    log "Unloading existing ${label}..."
    "$LAUNCHCTL" bootout "${GUI_DOMAIN}/${label}" 2>/dev/null || true
    if ! wait_pid_exit "$old_pid" "$STOP_TIMEOUT"; then
      error "Old process (PID ${old_pid}) did not exit within ${STOP_TIMEOUT}s — NOT bootstrapping (double-instance risk). Manual intervention required."
    fi
  fi

  generate_plist "$daemon_key" "$manifest" || error "plist generation failed for ${daemon_key}"

  local plist
  plist=$(plist_path "$daemon_key")
  "$LAUNCHCTL" bootstrap "$GUI_DOMAIN" "$plist"
  log "Registered: ${label}"

  # Verify. FLY-247 R1#1: failure paths now exit non-zero (the old
  # WARNING-and-return-0 silently reported success on a dead Lead).
  sleep 2
  if is_loaded "$daemon_key"; then
    local pid
    pid=$(get_launchd_pid "$daemon_key")
    if [ "$pid" = "0" ] || [ -z "$pid" ]; then
      error "${label} loaded but no PID — Lead did not start. Check: launchctl print ${GUI_DOMAIN}/${label}"
    fi
    log "Lead '${lead_id}' (${daemon_key}) daemon installed and running (PID: ${pid})."
  else
    error "${label} registered but not running. Check: launchctl print ${GUI_DOMAIN}/${label}"
  fi
}

cmd_uninstall() {
  local target="${1:---all}"

  if [ "$target" = "--all" ]; then
    local count=0
    # Uninstall all known manifests
    for manifest in $(list_manifests); do
      local daemon_key
      daemon_key=$(daemon_key_from_manifest "$manifest")
      uninstall_one "$daemon_key"
      count=$((count + 1))
    done
    # Also check for orphaned plists (no manifest but plist exists)
    for plist in "${PLIST_DIR}/${PLIST_PREFIX}".*.plist; do
      [ -f "$plist" ] || continue
      local label
      label=$(basename "$plist" .plist)
      local daemon_key="${label#${PLIST_PREFIX}.}"
      if [ ! -f "${MANIFEST_DIR}/${daemon_key}.json" ]; then
        log "Removing orphaned plist: ${plist}"
        "$LAUNCHCTL" bootout "${GUI_DOMAIN}/${label}" 2>/dev/null || true
        rm -f "$plist"
        count=$((count + 1))
      fi
    done
    log "Uninstalled ${count} Lead daemon(s)."
  else
    local manifests
    manifests=$(find_manifests "$target") || error "No manifest for '${target}' in ${MANIFEST_DIR}/"
    while IFS= read -r manifest; do
      local daemon_key
      daemon_key=$(daemon_key_from_manifest "$manifest")
      uninstall_one "$daemon_key"
    done <<< "$manifests"
  fi
}

uninstall_one() {
  local daemon_key="$1"
  local label
  label=$(plist_label "$daemon_key")
  local plist
  plist=$(plist_path "$daemon_key")

  if is_loaded "$daemon_key"; then
    "$LAUNCHCTL" bootout "${GUI_DOMAIN}/${label}" 2>/dev/null || true
    log "Unloaded: ${label}"
  fi

  if [ -f "$plist" ]; then
    rm -f "$plist"
    log "Removed: ${plist}"
  fi

  log "Daemon '${daemon_key}' uninstalled."
}

cmd_restart() {
  local target="${1:---all}"

  if [ "$target" = "--all" ]; then
    for manifest in $(list_manifests); do
      local daemon_key
      daemon_key=$(daemon_key_from_manifest "$manifest")
      restart_one "$daemon_key"
    done
  else
    local manifests
    manifests=$(find_manifests "$target") || error "No manifest for '${target}' in ${MANIFEST_DIR}/"
    while IFS= read -r manifest; do
      local daemon_key
      daemon_key=$(daemon_key_from_manifest "$manifest")
      restart_one "$daemon_key"
    done <<< "$manifests"
  fi
}

restart_one() {
  local daemon_key="$1"
  local label
  label=$(plist_label "$daemon_key")

  if ! is_loaded "$daemon_key"; then
    log "Daemon '${daemon_key}' is not loaded. Use 'install' first."
    return 1
  fi

  log "Restarting ${daemon_key}..."
  "$LAUNCHCTL" kickstart -k "${GUI_DOMAIN}/${label}"
  sleep 2
  local pid
  pid=$(get_launchd_pid "$daemon_key")
  log "Daemon '${daemon_key}' restarted (PID: ${pid})."
}

cmd_status() {
  require_jq

  local has_leads=false

  printf "\n%-18s  %-14s  %-18s  %-8s  %s\n" "DAEMON KEY" "LEAD" "LAUNCHD" "PID" "LOG"
  printf "%-18s  %-14s  %-18s  %-8s  %s\n" "──────────" "────" "───────" "───" "───"

  # Check all manifests
  for f in "${MANIFEST_DIR}"/*.json; do
    [ -f "$f" ] || continue
    has_leads=true
    local daemon_key
    daemon_key=$(daemon_key_from_manifest "$f")
    local lead_id
    lead_id=$(jq -r '.leadId' "$f")

    local state="not installed"
    local pid="--"
    local logfile
    logfile=$(log_path "$daemon_key")

    if [ -f "$(plist_path "$daemon_key")" ]; then
      if is_loaded "$daemon_key"; then
        pid=$(get_launchd_pid "$daemon_key")
        if [ "$pid" != "0" ] && [ -n "$pid" ]; then
          state="running"
        else
          state="loaded (idle)"
          pid="--"
        fi
      else
        state="installed (unloaded)"
      fi
    fi

    local log_info="--"
    if [ -f "$logfile" ]; then
      local size
      size=$(wc -c < "$logfile" | tr -d ' ')
      local human_size
      if (( size > 1048576 )); then
        human_size="$((size / 1048576))M"
      elif (( size > 1024 )); then
        human_size="$((size / 1024))K"
      else
        human_size="${size}B"
      fi
      log_info="${logfile} (${human_size})"
    fi

    printf "%-18s  %-14s  %-18s  %-8s  %s\n" "$daemon_key" "$lead_id" "$state" "$pid" "$log_info"
  done

  if [ "$has_leads" = false ]; then
    log "No manifests found. Run claude-lead.sh first to generate manifests."
  fi

  echo ""

  # Also show other flywheel launchd services
  printf "Other Flywheel services:\n"
  for label in com.flywheel.daily-standup com.flywheel.updater; do
    local svc_state="not loaded"
    if "$LAUNCHCTL" print "${GUI_DOMAIN}/${label}" &>/dev/null; then
      svc_state="loaded"
    fi
    printf "  %-32s  %s\n" "$label" "$svc_state"
  done
  echo ""
}

cmd_logs() {
  local target="${1:-}"
  if [ -z "$target" ]; then
    error "Usage: flywheel-daemon.sh logs <lead-id>"
  fi

  require_jq

  # Resolve to daemon key
  local manifests
  manifests=$(find_manifests "$target") || error "No manifest for '${target}'"
  local manifest
  manifest=$(echo "$manifests" | head -1)
  local daemon_key
  daemon_key=$(daemon_key_from_manifest "$manifest")

  local logfile
  logfile=$(log_path "$daemon_key")
  if [ ! -f "$logfile" ]; then
    error "Log file not found: ${logfile}"
  fi

  log "Tailing ${logfile} (Ctrl+C to stop)..."
  tail -f "$logfile"
}

