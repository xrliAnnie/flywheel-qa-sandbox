reference_build_projects() {
  jq -n \
    --arg projectName "$1" \
    --arg projectRoot "$2" \
    --arg projectRepo "$3" \
    --arg agentId "$4" \
    --arg chatChannel "$5" \
    --arg botTokenEnv "$6" \
    --arg slotRole "$7" \
    '
  [
    ({
      projectName: $projectName,
      projectRoot: $projectRoot,
      projectRepo: $projectRepo,
      leads: [
        {
          agentId: $agentId,
          summaryRole: "exempt",
          chatChannel: $chatChannel,
          botTokenEnv: $botTokenEnv,
          match: { labels: ["*"] }
        }
      ]
    })
    | if $slotRole == "cos" then . + { generalChannel: $chatChannel } else . end
  ]
  '
}

