# valid → JSON with slotId + deptLabel + resolved fields
if v="$(qa_multilead_validate_campaign_args "$SLOTS" slot 2 "3:Ops-Test" 2>/dev/null)"; then
  jq -e 'length == 1 and .[0].slotId == 3 and .[0].deptLabel == "Ops-Test" and .[0].agentId == "flywheel-test-3" and .[0].tokenEnvVar == "TEST_BOT_TOKEN_3" and .[0].chatChannel == "chan-3"' \
    >/dev/null 2>&1 <<<"$v" || { C4_OK=0; fail "C4: valid campaign args JSON wrong: $v"; }
else
  C4_OK=0; fail "C4: valid campaign args should pass"
fi
[[ "$C4_OK" == "1" ]] && pass "C4: campaign args validation matrix"

# ── Lock tests — all against a temp lock root ──
LOCK_ROOT="${TMP}/locks"
mkdir -p "$LOCK_ROOT"
STALE_PROBE="${TMP}/stale-invoked"
stale_probe() { echo "$1" >> "$STALE_PROBE"; }

# D2: claim-set success (run before D1 so the root starts clean)
rm -rf "${LOCK_ROOT:?}"/* "$STALE_PROBE"
if out="$(qa_multilead_claim_set "$LOCK_ROOT" stale_probe 3 2)"; then
  D2_OK=1
  [[ -d "${LOCK_ROOT}/flywheel-test-slot-2.lock" && -d "${LOCK_ROOT}/flywheel-test-slot-3.lock" ]] \
    || { D2_OK=0; fail "D2: both locks should exist"; }
  [[ "$(cat "${LOCK_ROOT}/flywheel-test-slot-2.lock/pid")" == "claiming" ]] \
    || { D2_OK=0; fail "D2: lock pid should be 'claiming'"; }
  # sorted order in output (2 before 3 even though passed 3 2)
  first="$(head -1 <<<"$out")"
  [[ "$first" == *"slot-2.lock" ]] || { D2_OK=0; fail "D2: claim order should be sorted (got first=$first)"; }
  [[ "$D2_OK" == "1" ]] && pass "D2: claim-set claims all slots sorted"
else
  fail "D2: claim-set on free slots should succeed"
fi

# D1: second slot already locked (live PID) → zero side effects
rm -rf "${LOCK_ROOT:?}"/* "$STALE_PROBE"
mkdir -p "${LOCK_ROOT}/flywheel-test-slot-3.lock"
echo "$$" > "${LOCK_ROOT}/flywheel-test-slot-3.lock/pid"
if qa_multilead_claim_set "$LOCK_ROOT" stale_probe 2 3 >/dev/null 2>&1; then
  fail "D1: claim-set should fail when slot 3 is held live"
else
  D1_OK=1
  [[ ! -d "${LOCK_ROOT}/flywheel-test-slot-2.lock" ]] || { D1_OK=0; fail "D1: slot-2 lock must be rolled back"; }
  [[ "$(cat "${LOCK_ROOT}/flywheel-test-slot-3.lock/pid")" == "$$" ]] || { D1_OK=0; fail "D1: slot-3 lock must be untouched"; }
  [[ ! -f "$STALE_PROBE" ]] || { D1_OK=0; fail "D1: stale teardown must NOT run for a live lock"; }
  [[ "$D1_OK" == "1" ]] && pass "D1: blocked claim-set → zero side effects"
fi

# E1: partial failure (3rd of 3 held) → first two rolled back
rm -rf "${LOCK_ROOT:?}"/* "$STALE_PROBE"
mkdir -p "${LOCK_ROOT}/flywheel-test-slot-4.lock"
echo "$$" > "${LOCK_ROOT}/flywheel-test-slot-4.lock/pid"
if qa_multilead_claim_set "$LOCK_ROOT" stale_probe 2 3 4 >/dev/null 2>&1; then
  fail "E1: claim-set should fail when slot 4 is held"
else
  E1_OK=1
  [[ ! -d "${LOCK_ROOT}/flywheel-test-slot-2.lock" ]] || { E1_OK=0; fail "E1: slot-2 must be rolled back"; }
  [[ ! -d "${LOCK_ROOT}/flywheel-test-slot-3.lock" ]] || { E1_OK=0; fail "E1: slot-3 must be rolled back"; }
  [[ -d "${LOCK_ROOT}/flywheel-test-slot-4.lock" ]] || { E1_OK=0; fail "E1: slot-4 (pre-held) must survive"; }
  [[ "$E1_OK" == "1" ]] && pass "E1: partial claim failure → full rollback"
fi

# F1: finalize + is_borrowed
rm -rf "${LOCK_ROOT:?}"/* "$STALE_PROBE"
qa_multilead_claim_set "$LOCK_ROOT" stale_probe 2 3 >/dev/null
if qa_multilead_finalize_locks "$LOCK_ROOT" "$$" 2 "camp-1" 2 3; then
  F1_OK=1
  [[ "$(cat "${LOCK_ROOT}/flywheel-test-slot-2.lock/pid")" == "$$" ]] || { F1_OK=0; fail "F1: owner lock pid must be Bridge PID"; }
  [[ "$(cat "${LOCK_ROOT}/flywheel-test-slot-3.lock/pid")" == "$$" ]] || { F1_OK=0; fail "F1: borrowed lock pid must be Bridge PID"; }
  if qa_multilead_lock_is_borrowed "${LOCK_ROOT}/flywheel-test-slot-2.lock" >/dev/null 2>&1; then
    F1_OK=0; fail "F1: owner lock must NOT read as borrowed"
  fi
  owner="$(qa_multilead_lock_is_borrowed "${LOCK_ROOT}/flywheel-test-slot-3.lock" 2>/dev/null)" \
    && [[ "$owner" == "2" ]] || { F1_OK=0; fail "F1: borrowed lock must point at owner slot 2 (got '${owner:-}')"; }
  [[ "$F1_OK" == "1" ]] && pass "F1: finalize writes Bridge PID + borrowed sidecar semantics"
else
  fail "F1: finalize_locks should succeed"
fi

# H1: borrowed lock, LIVE Bridge PID, mtime aged >300s → claim refuses, lock intact
touch -t 202601010000 "${LOCK_ROOT}/flywheel-test-slot-3.lock/pid" 2>/dev/null || true
if qa_multilead_claim_one "${LOCK_ROOT}/flywheel-test-slot-3.lock" stale_probe 3 >/dev/null 2>&1; then
  fail "H1: claim of a live-campaign borrowed lock must fail"
else
  H1_OK=1
  [[ "$(cat "${LOCK_ROOT}/flywheel-test-slot-3.lock/pid")" == "$$" ]] || { H1_OK=0; fail "H1: lock pid must be unchanged"; }
  [[ ! -f "$STALE_PROBE" ]] || { H1_OK=0; fail "H1: stale teardown must NOT run"; }
  [[ "$H1_OK" == "1" ]] && pass "H1: aged borrowed lock w/ live Bridge PID survives reclaim attempt"
fi

# H2: borrowed lock with DEAD pid → refuse AND never invoke stale teardown
rm -rf "${LOCK_ROOT:?}"/* "$STALE_PROBE"
mkdir -p "${LOCK_ROOT}/flywheel-test-slot-3.lock"
DEAD_PID=99999
while kill -0 "$DEAD_PID" 2>/dev/null; do DEAD_PID=$((DEAD_PID - 1)); done
echo "$DEAD_PID" > "${LOCK_ROOT}/flywheel-test-slot-3.lock/pid"
jq -n '{ownerSlot: 2, campaignId: "camp-x", borrowed: true}' > "${LOCK_ROOT}/flywheel-test-slot-3.lock/campaign.json"
if qa_multilead_claim_one "${LOCK_ROOT}/flywheel-test-slot-3.lock" stale_probe 3 >/dev/null 2>&1; then
  fail "H2: dead borrowed lock must not be silently reclaimed"
else
  H2_OK=1
  [[ ! -f "$STALE_PROBE" ]] || { H2_OK=0; fail "H2: stale teardown must NOT be invoked on a borrowed lock"; }
  [[ -d "${LOCK_ROOT}/flywheel-test-slot-3.lock" ]] || { H2_OK=0; fail "H2: borrowed lock must stay for owner teardown"; }
  [[ "$H2_OK" == "1" ]] && pass "H2: dead borrowed lock → fail-loud, no stale teardown"
fi

# ── F2: manifest-driven extra-Lead teardown ──
FAKEHOME="${TMP}/home"
mkdir -p "${FAKEHOME}/.flywheel/pids" "${FAKEHOME}/.flywheel/claude-sessions" \
  "${FAKEHOME}/.flywheel/manifests" "${FAKEHOME}/.flywheel/lead-workspace/flywheel-test-3"
# Orphaned spawn (NOT a child of this shell): a killed direct child stays a
# zombie until reaped, and `kill -0 <zombie>` still succeeds — which would
# false-fail the "supervisor killed" assertion. Reparenting to init makes the
# kill observable.
SUP_PID=$(bash -c 'sleep 300 >/dev/null 2>&1 & echo $!')
echo "$SUP_PID" > "${FAKEHOME}/.flywheel/pids/test-slot-2-flywheel-test-3.pid"
echo "sess-id" > "${FAKEHOME}/.flywheel/claude-sessions/test-slot-2-flywheel-test-3.session-id"
echo "{}" > "${FAKEHOME}/.flywheel/manifests/test-slot-2-flywheel-test-3.json"
echo "w" > "${FAKEHOME}/.flywheel/lead-workspace/flywheel-test-3/f.txt"
CAMPAIGN_MANIFEST="${TMP}/campaign-manifest.json"
jq -n \
  --arg pf "${FAKEHOME}/.flywheel/pids/test-slot-2-flywheel-test-3.pid" \
  --arg sf "${FAKEHOME}/.flywheel/claude-sessions/test-slot-2-flywheel-test-3.session-id" \
  --arg lm "${FAKEHOME}/.flywheel/manifests/test-slot-2-flywheel-test-3.json" \
  --arg lw "${FAKEHOME}/.flywheel/lead-workspace/flywheel-test-3" \
  '{
    campaignId: "camp-1", ownerSlot: 2, projectName: "test-slot-2",
    borrowedSlots: [3],
    extraLeads: [{
      slotId: 3, agentId: "flywheel-test-3", deptLabel: "Ops-Test",
      chatChannelId: "chan-3", botTokenEnv: "TEST_BOT_TOKEN_3",
      tmuxWindow: "test-slot-2-flywheel-test-3",
      pidFile: $pf, sessionIdFile: $sf, leadManifest: $lm, leadWorkspace: $lw
    }]
  }' > "$CAMPAIGN_MANIFEST"
qa_multilead_teardown_extra_leads "$CAMPAIGN_MANIFEST" >/dev/null 2>&1
F2_OK=1
sleep 0.3
kill -0 "$SUP_PID" 2>/dev/null && { F2_OK=0; fail "F2: supervisor pid should be killed"; kill -9 "$SUP_PID" 2>/dev/null; }
