# FLY-1189 H1: hermetic tests for the multi-Lead additive extension of
# scripts/test-deploy.sh / scripts/test-teardown.sh (lib: scripts/lib/qa-multilead.sh).
#
#   A1  FLYWHEEL_PROJECTS builder byte-compat (slotRole=lead, no new flags)
#   A2  FLYWHEEL_PROJECTS builder byte-compat (slotRole=cos → generalChannel)
