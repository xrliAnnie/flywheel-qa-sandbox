import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { planGuard, git, env, put } from './guard-model.mjs';
const here = path.dirname(fileURLToPath(import.meta.url));
const originalXdg = env.XDG_CONFIG_HOME;
const results = [];
for (const mode of ['assume-unchanged-ignore', 'skip-worktree-ignore', 'untracked-ignore-clean', 'default-excludes-in-worktree']) {
 const root = fs.mkdtempSync(path.join(here, mode + '-'));
 git(root, 'init', '-q', '-b', 'main');
 git(root, 'config', 'user.name', 'Review'); git(root, 'config', 'user.email', 'review@example.invalid');
 put(root, 'tracked', 'H\n');
 if (mode !== 'untracked-ignore-clean') put(root,'.gitignore','# base\n');
 if (mode === 'default-excludes-in-worktree') put(root,'xdg/git/ignore','drafts/\n');
 git(root,'add','.'); git(root,'commit','-qm','H');
 const H=git(root,'rev-parse','HEAD').trim();
 put(root,'tracked','S\n');
 if (mode === 'default-excludes-in-worktree') put(root,'xdg/git/ignore','# removed\n');
 git(root,'add','.'); git(root,'commit','-qm','S');
 const S=git(root,'rev-parse','HEAD').trim();
 git(root,'reset','--hard',H);
 if (mode === 'default-excludes-in-worktree') env.XDG_CONFIG_HOME=path.join(root,'xdg');
 else put(root,'.gitignore','drafts/\n');
 if (mode === 'assume-unchanged-ignore') git(root,'update-index','--assume-unchanged','.gitignore');
 if (mode === 'skip-worktree-ignore') git(root,'update-index','--skip-worktree','.gitignore');
 put(root,'drafts/unpublished.md','UNIQUE NEVER COMMITTED\n');
 const beforeStatus=git(root,'status','--porcelain=v2','--untracked-files=all');
 const checkIgnore=git(root,'check-ignore','--no-index','-v','drafts/unpublished.md');
 const guard=planGuard(root,H,S);
 const reset=git(root,'reset','--hard',S);
 const afterReset=fs.existsSync(path.join(root,'drafts/unpublished.md'));
 const ignoreAfterReset=fs.readFileSync(path.join(root,mode === 'default-excludes-in-worktree' ? 'xdg/git/ignore' : '.gitignore'),'utf8');
 const clean=git(root,'clean','-fd');
 const afterClean=fs.existsSync(path.join(root,'drafts/unpublished.md'));
 const finalStatus=git(root,'status','--porcelain=v2','--untracked-files=all');
 const result={mode,root,H,S,beforeStatus,checkIgnore,guard,reset,afterReset,ignoreAfterReset,clean,afterClean,finalStatus};
 results.push(result); console.log(JSON.stringify(result));
 if (originalXdg === undefined) delete env.XDG_CONFIG_HOME; else env.XDG_CONFIG_HOME=originalXdg;
}
fs.writeFileSync(path.join(here,'boundary-results.json'),JSON.stringify(results,null,2)+'\n');
