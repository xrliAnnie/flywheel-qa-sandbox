import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { createRequire } from 'node:module';
const packageRequire = createRequire(process.env.FLYWHEEL_HTML_TEST_PACKAGE_JSON || new URL('../../../packages/teamlead/package.json', import.meta.url));
const { Window } = await import(packageRequire.resolve('happy-dom'));
const html = readFileSync(new URL('./founder-design.html', import.meta.url), 'utf8');
const marker = '【页面意见汇总】FLY-2519';
assert.equal((html.match(/<script\b/g) || []).length, 1);
assert.match(html, /<script nonce="__CSP_NONCE__">/);
assert.doesNotMatch(html, /http-equiv=["']Content-Security-Policy/i);
assert.doesNotMatch(html, /\son[a-z]+\s*=/i);
assert.doesNotMatch(html, /<(?:script|link|img|iframe)[^>]*(?:src|href)\s*=\s*["']https?:/i);
assert.doesNotMatch(html, /innerHTML/);
assert.equal((html.match(/DIAGRAM PENDING LOCAL RENDER/g) || []).length, 2);
const script = html.match(/<script nonce="__CSP_NONCE__">([\s\S]*?)<\/script>/)[1];
function make(path) {
 const win = new Window({url:'https://reports.example.test/'+path});
 win.document.write(html.replace(/<script[\s\S]*?<\/script>/, ''));
 win.eval(script);return win;
}
const win = make('FLY-2519');
const doc = win.document;
assert.equal(doc.querySelectorAll('section').length, doc.querySelectorAll('[data-comment]').length);
const input = doc.querySelector('[data-comment]');
input.value = '<img src=x onerror=alert(1)> 设计意见';
input.dispatchEvent(new win.Event('input'));
assert.equal(win.localStorage.getItem('flywheel-comments:/FLY-2519:goal'),input.value);
assert.match(doc.querySelector('#chunks').textContent, /设计意见/);
assert.equal(doc.querySelectorAll('#chunks img').length,0);
assert.ok(doc.querySelector('#chunks pre').textContent.startsWith(marker+'\n'));
const copies=[];
Object.defineProperty(win.navigator,'clipboard',{configurable:true,value:{writeText:async text=>copies.push(text)}});
doc.querySelector('#copy-all').click();await new Promise(resolve=>setTimeout(resolve,0));
assert.equal(copies.length,1);
let fallbacks=0;
doc.execCommand=command=>{assert.equal(command,'copy');fallbacks++;return true;};
Object.defineProperty(win.navigator,'clipboard',{configurable:true,value:{writeText:async()=>{throw new Error('denied');}}});
doc.querySelector('#copy-all').click();await new Promise(resolve=>setTimeout(resolve,0));
assert.equal(fallbacks,1);
Object.defineProperty(win.navigator,'clipboard',{configurable:true,value:undefined});
doc.querySelector('#copy-all').click();await new Promise(resolve=>setTimeout(resolve,0));
assert.equal(fallbacks,2);
input.value='很长😀'.repeat(2500);input.dispatchEvent(new win.Event('input'));
const chunks=Array.from(doc.querySelectorAll('#chunks pre'),node=>node.textContent);
assert.ok(chunks.length>1);
for(const chunk of chunks){assert.ok(chunk.startsWith(marker+'\n'));assert.ok(Array.from(chunk).length<=1800);}
assert.equal(doc.querySelectorAll('#chunks button').length,chunks.length);
const other=make('different-report');assert.equal(other.document.querySelector('[data-comment]').value,'');
const blocked = new Window({url:'https://reports.example.test/blocked'});
blocked.document.write(html.replace(/<script[\s\S]*?<\/script>/,''));
Object.defineProperty(blocked,'localStorage',{get(){throw new Error('storage denied');}});
blocked.eval(script);const b=blocked.document.querySelector('[data-comment]');b.value='仍可汇总';b.dispatchEvent(new blocked.Event('input'));
assert.match(blocked.document.querySelector('#chunks').textContent,/仍可汇总/);
win.close();other.close();blocked.close();
console.log('PASS: sections, nonce, escaping, storage scope/failure, summary marker, Unicode chunks, clipboard success/absence/rejection.');
