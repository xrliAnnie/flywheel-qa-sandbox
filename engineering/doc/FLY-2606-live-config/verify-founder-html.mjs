import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
const { Window } = await import(process.env.FLY2606_HAPPY_DOM_MODULE || 'happy-dom');
const html = readFileSync(new URL('./founder-report.html', import.meta.url), 'utf8');
assert.equal((html.match(/<script\b/g) || []).length, 1);
assert.equal((html.match(/nonce="__CSP_NONCE__"/g) || []).length, 1);
assert(!/\son\w+\s*=|Content-Security-Policy|<script[^>]+src=|<link\b|<iframe\b/i.test(html));
assert(!/https?:\/\/|url\(/i.test(html));
const source = html.match(/<script nonce="__CSP_NONCE__">([\s\S]*?)<\/script>/)[1];
const marker = '【页面意见汇总】FLY-2606';
const w = new Window({ url: 'https://reports.example/FLY-2606/report.html' });
w.document.write(html.replace(/<script[\s\S]*?<\/script>/, ''));
let fallbacks = 0;
w.document.execCommand = () => { fallbacks++; return true; };
Object.defineProperty(w.navigator, 'clipboard', { configurable: true, value: { writeText: async () => { throw new Error('denied'); } } });
w.eval(source);
const notes = [...w.document.querySelectorAll('.note')];
assert.equal(notes.length, w.document.querySelectorAll('section').length);
assert.equal(notes.length, 8);
notes[0].value = '验证意见'; notes[0].dispatchEvent(new w.Event('input'));
assert.equal(w.localStorage.getItem('fly2606:/FLY-2606/report.html:summary'), '验证意见');
notes[1].value = '长意见'.repeat(1800); notes[1].dispatchEvent(new w.Event('input'));
const chunks = [...w.document.querySelectorAll('#chunks textarea')].map(x => x.value);
assert(chunks.length > 1);
for (const c of chunks) { assert(c.startsWith(marker + '\n')); assert(c.length <= 1800); }
assert(chunks[0].includes('【改完就用，生效有据】'));
assert.equal(chunks.join('').match(/长意见/g).length, 1800);
w.document.querySelector('#copy-all').click(); await new Promise(r => setTimeout(r, 10)); assert.equal(fallbacks, 1);
Object.defineProperty(w.navigator, 'clipboard', { value: undefined });
w.document.querySelector('#copy-all').click(); await new Promise(r => setTimeout(r, 10)); assert.equal(fallbacks, 2);
Object.defineProperty(w, 'localStorage', { get() { throw new Error('blocked'); } });
notes[2].value = '<img src=x onerror=alert(1)>'; notes[2].dispatchEvent(new w.Event('input'));
assert.equal(w.document.querySelectorAll('img').length, 0);
const w2 = new Window({ url: 'https://reports.example/other-report.html' });
w2.document.write(html.replace(/<script[\s\S]*?<\/script>/, ''));
w2.localStorage.setItem('fly2606:/FLY-2606/report.html:summary', 'should not leak');
w2.eval(source);
assert.equal(w2.document.querySelector('.note').value, '');
console.log(JSON.stringify({ structural: 'PASS', controller: 'PASS', sections: notes.length, chunks: chunks.length, clipboard_rejection_fallback: true, clipboard_absent_fallback: true, storage_failure_safe: true, report_path_isolation: true, visual_browser: 'NOT_RUN', diagrams: 'PENDING_LOCAL_RENDER' }));
await w.happyDOM.close(); await w2.happyDOM.close();
